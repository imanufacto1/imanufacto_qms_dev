async function seed() {
  console.log('Seeding reports with industry-standard templates...');
  
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL is not defined');
  }

  const db = await getDb();

  for (const report of reportList) {
    const code = report.name.toUpperCase().replace(/[^A-Z0-9]/g, '_');
    const templateKey = getTemplateKey(report.name);
    const templateContent = TEMPLATES[templateKey];

    console.log(`Processing ${report.name} -> Template: ${templateKey}`);

    // Check if exists
    const existing = await db.select()
      .from(reports)
      .where(eq(reports.reportCode, code))
      .limit(1);

    const reportData = {
      reportName: report.name,
      reportCode: code,
      reportType: report.type,
      status: 'Active',
      schedulerStatus: 'Inactive',
      isCurrent: true,
      version: 1,
      templateContent: templateContent,
      headerContent: sampleHeader,
      footerContent: sampleFooter,
      pageSetup: {
        paperFormat: 'A4',
        orientation: 'Portrait',
        headerHeight: 2.5,
        footerHeight: 2,
        margin: 1,
        waitForJavascript: false
      }
    };

    if (existing.length === 0) {
      await db.insert(reports).values(reportData);
    } else {
      await db.update(reports)
        .set(reportData)
        .where(eq(reports.reportCode, code));
    }
  }

  console.log('Reports seeded/updated successfully.');
  process.exit(0);
}

seed().catch((err) => {
  console.error('Seeding failed:', err);
  process.exit(1);
});
