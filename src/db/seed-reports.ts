// Map Report Name/Pattern to Template Key
function getTemplateKey(name: string): string {
  const n = name.toUpperCase();
  if (n.includes('OBJECTIVE')) return 'OBJECTIVE';
  if (n.includes('NON CONFORMANCE') || n.includes('NON-CONFORMANCE')) return 'NON_CONFORMANCE';
  if (n.includes('RISK') && n.includes('OPPORTUNITY')) return 'RISK_AND_OPPORTUNITY';
  if (n.includes('TRAINING')) return 'TRAINING';
  if (n.includes('SUPPLIER')) return 'SUPPLIER';
  if (n.includes('KPI')) return 'KPI_REPORT';
  if (n.includes('STATEMENT OF APPLICABILITY')) return 'STATEMENT_OF_APPLICABILITY';
  if (n.includes('HAZARD') || (n.includes('RISK') && n.includes('IDENTIFIED'))) return 'HAZARD_AND_RISK';
  if (n.includes('ACCIDENT') || n.includes('INCIDENT') && !n.includes('ISMS')) return 'ACCIDENT_INCIDENT';
  if (n.includes('DRILL') || n.includes('EMERGENCY') && !n.includes('PLAN')) return 'EMERGENCY_DRILL';
  if (n.includes('EMERGENCY') && n.includes('PLAN')) return 'EMERGENCY_PLAN';
  if (n.includes('ISMS RISK') || n.includes('INFORMATION SECURITY RISK')) return 'ISMS_RISK';
  if (n.includes('ASSET')) return 'ISMS_ASSET';
  if (n.includes('BUSINESS CONTINUITY')) return 'BUSINESS_CONTINUITY';
  if (n.includes('DOCUMENTS')) return 'DOCUMENTS_CONTROL';
  if (n.includes('ISMS') && n.includes('INCIDENT')) return 'ISMS_INCIDENT';
  if (n.includes('CCP')) return 'CCP_MONITORING';
  if (n.includes('HYGIENE')) return 'HYGIENE_INSPECTION';
  if (n.includes('FMEA')) return 'FMEA_REPORT';
  if (n.includes('CONTROL PLAN')) return 'CONTROL_PLAN';
  if (n.includes('VDA')) return 'VDA_PROCESS_AUDIT';
  
  return 'GENERIC';
}

